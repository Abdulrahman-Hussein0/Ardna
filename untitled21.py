import re
import gradio as gr

AR = {"maize": "ذرة", "wheat": "قمح", "rice": "أرز", "apples": "تفاح",
      "potatoes": "بطاطس", "tomatoes": "طماطم", "onions": "بصل",
      "oranges, mandarines": "برتقال ويوسفي"}

GOV_AR = {"Minya": "المنيا", "Beheira": "البحيرة", "Menoufia": "المنوفية",
          "Sharqia": "الشرقية", "Aswan": "أسوان"}

def norm(s):
    s = re.sub(r"[\u064b-\u065f]", "", s)
    for a, b in {"أ": "ا", "إ": "ا", "آ": "ا", "ة": "ه", "ى": "ي"}.items():
        s = s.replace(a, b)
    return s.strip().lower()

GOV_KEYS = {norm(ar): en for en, ar in GOV_AR.items()}
GOV_KEYS.update({en.lower(): en for en in GOV_AR})
state = {"gov": None}

def find_gov(msg):
    m = norm(msg)
    for k, en in GOV_KEYS.items():
        if k in m:
            return en
    return None

def tips(gov):
    others = [g for g in GOV_AR if g != gov]
    return ("\n\n---\nممكن تسألني: **ليه الذرة؟** · **إيه اللي أصدّره؟** · "
            f"أو جرّب محافظة تانية زي **{GOV_AR[others[-1]]}**")

def chat(message, history):
    m = norm(message)
    gov = find_gov(message)
    if gov:
        state["gov"] = gov
    gov = state["gov"]

    if gov is None:
        names = "، ".join(GOV_AR.values())
        return f"أهلاً! 🌱 اكتب اسم محافظتك وأقولك تزرع إيه.\n\nالمتاح دلوقتي: {names}"

    df = recommend_v2(gov)
    g = GOV_AR[gov]
    grow = df[df["score"] > 0].head(3)
    export = df[(df["deficit"] < 0.05) & (df["suitability"] >= 0.5)]

    if any(k in m for k in ["صدر", "تصدير"]):
        if export.empty:
            return f"في {g} مفيش محصول فايض ومناسب للتصدير في الداتا الحالية." + tips(gov)
        names = "، ".join(AR[c] for c in export["crop"])
        return (f"🚢 للتصدير من {g}: **{names}**\n\nمصر بتنتج منهم أكتر من احتياجها، "
                "وملاءمتهم لمناخ المحافظة كويسة." + tips(gov))

    if any(k in m for k in ["ليه", "لماذا", "سبب"]):
        top = grow.iloc[0]
        return (f"**{AR[top['crop']]}** في الأول لأن:\n"
                f"- مصر ناقصها **{top['deficit']:.0%}** من احتياجها منه (من داتا FAOSTAT)\n"
                f"- ومناسب لحرارة وتربة {g} بنسبة **{top['suitability']:.0%}**\n\n"
                f"الدرجة = العجز × الملاءمة = **{top['score']:.2f}**" + tips(gov))

    lines = [f"📍 **{g}**\n", "🌱 **ازرع:**"]
    for i, (_, r) in enumerate(grow.iterrows(), 1):
        lines.append(f"{i}. **{AR[r['crop']]}**: عجز {r['deficit']:.0%}، ملاءمة {r['suitability']:.0%}")
    if not export.empty:
        lines.append("\n🚢 **للتصدير:** " + "، ".join(AR[c] for c in export["crop"]))
    return "\n".join(lines) + tips(gov)

gr.close_all()
demo = gr.ChatInterface(
    fn=chat,
    title="🌱 مستشار المحاصيل",
    description="اكتب اسم محافظتك وأنا أقولك تزرع إيه، وإيه اللي تصدّره.",
    examples=["المنوفية", "أسوان", "المنيا"],
    cache_examples=False,
)
demo.launch(share=True)